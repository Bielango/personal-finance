CREATE TABLE IF NOT EXISTS USUARIO (
    USU_ID     INTEGER PRIMARY KEY AUTOINCREMENT,
    USU_NOME   VARCHAR(100) NOT NULL,
    USU_EMAIL  VARCHAR(100) NOT NULL,
    USU_SENHA  VARCHAR(100) NOT NULL, -- hash do bcrypt, nunca a senha pura

    CONSTRAINT UQ_USU_EMAIL UNIQUE (USU_EMAIL)
);

CREATE TABLE IF NOT EXISTS CONTA (
    CON_ID             INTEGER PRIMARY KEY AUTOINCREMENT,
    CON_NOME           VARCHAR(100) NOT NULL COLLATE NOCASE,
    CON_INSTITUICAO    VARCHAR(100),
    CON_TIPO           VARCHAR(20) NOT NULL,
    CON_SALDO          INTEGER NOT NULL, -- valor em centavos
    CON_USU_ID         INTEGER NOT NULL,

    CONSTRAINT CK_CON_TIPO CHECK (CON_TIPO IN ('corrente', 'poupanca', 'investimento', 'carteira')),
    CONSTRAINT UQ_CON_USUARIO_NOME UNIQUE (CON_USU_ID, CON_NOME),
    CONSTRAINT FK_CON_USUARIO FOREIGN KEY (CON_USU_ID)
        REFERENCES USUARIO (USU_ID) ON DELETE CASCADE
);

-- Tipos fixos de transação. Não há cadastro: as linhas abaixo são as únicas.
CREATE TABLE IF NOT EXISTS CATEGORIA (
    CAT_ID       INTEGER PRIMARY KEY,
    CAT_NOME     VARCHAR(100) NOT NULL,
    CAT_REPETIR  INTEGER NOT NULL,              -- 1 = pode ser paga mais de uma vez

    CONSTRAINT UQ_CAT_NOME UNIQUE (CAT_NOME),
    CONSTRAINT CK_CAT_REPETIR CHECK (CAT_REPETIR IN (0, 1))
);

INSERT OR IGNORE INTO CATEGORIA (CAT_ID, CAT_NOME, CAT_REPETIR)
VALUES (1, 'Única', 0), (2, 'Recorrente', 1);

CREATE TABLE IF NOT EXISTS TRANSACAO (
    TRA_ID           INTEGER PRIMARY KEY AUTOINCREMENT,
    TRA_CON_ID       INTEGER NOT NULL,
    TRA_CAT_ID       INTEGER NOT NULL,
    TRA_TITULO       VARCHAR(100) NOT NULL,
    TRA_DESCRICAO    TEXT,
    TRA_OPERACAO     CHAR(1) NOT NULL,              -- + = recebimento, - = gasto
    TRA_VALOR        INTEGER NOT NULL,              -- valor em centavos, sempre positivo
    TRA_STATUS       CHAR(1) NOT NULL DEFAULT 'a',  -- a = ativa, p = paga, c = cancelada
    TRA_DATA_INICIO  DATETIME NOT NULL DEFAULT (datetime('now', 'localtime')),
    TRA_DATA_FIM     DATETIME,                      -- último pagamento ou cancelamento

    CONSTRAINT CK_TRA_OPERACAO CHECK (TRA_OPERACAO IN ('+', '-')),
    CONSTRAINT CK_TRA_VALOR CHECK (TRA_VALOR > 0),
    CONSTRAINT CK_TRA_STATUS CHECK (TRA_STATUS IN ('a', 'p', 'c')),
    CONSTRAINT FK_TRA_CONTA FOREIGN KEY (TRA_CON_ID)
        REFERENCES CONTA (CON_ID) ON DELETE RESTRICT,
    CONSTRAINT FK_TRA_CATEGORIA FOREIGN KEY (TRA_CAT_ID)
        REFERENCES CATEGORIA (CAT_ID) ON DELETE RESTRICT
);

-- Deixa rápida a listagem por período.
CREATE INDEX IF NOT EXISTS IX_TRA_DATA_INICIO ON TRANSACAO (TRA_DATA_INICIO);

CREATE TABLE IF NOT EXISTS AGENDAMENTO (
    AGE_ID           INTEGER PRIMARY KEY AUTOINCREMENT,
    AGE_CON_ID       INTEGER NOT NULL REFERENCES CONTA (CON_ID) ON DELETE RESTRICT,
    AGE_TITULO       VARCHAR(100) NOT NULL,
    AGE_DESCRICAO    TEXT,
    AGE_OPERACAO     CHAR(1) NOT NULL CHECK (AGE_OPERACAO IN ('+', '-')),
    AGE_VALOR        INTEGER NOT NULL CHECK (AGE_VALOR > 0),
    AGE_TIPO         VARCHAR(12) NOT NULL CHECK (AGE_TIPO IN ('parcelado', 'recorrente')),
    AGE_PRIMEIRO     TEXT NOT NULL,
    AGE_PERIODICIDADE VARCHAR(8) CHECK (AGE_PERIODICIDADE IN ('semanal', 'mensal', 'anual')),
    AGE_PARCELAS     INTEGER CHECK (AGE_PARCELAS BETWEEN 2 AND 120),
    AGE_ATE          TEXT,
    AGE_CANCELADO    INTEGER NOT NULL DEFAULT 0 CHECK (AGE_CANCELADO IN (0, 1)),

    CONSTRAINT CK_AGE_TIPO CHECK (
        (AGE_TIPO = 'parcelado' AND AGE_PARCELAS IS NOT NULL AND AGE_VALOR >= AGE_PARCELAS
         AND AGE_PERIODICIDADE IS NULL AND AGE_ATE IS NULL)
        OR (AGE_TIPO = 'recorrente' AND AGE_PARCELAS IS NULL AND AGE_PERIODICIDADE IS NOT NULL
            AND (AGE_ATE IS NULL OR AGE_ATE >= AGE_PRIMEIRO))
    )
);

CREATE TABLE IF NOT EXISTS OCORRENCIA (
    OCO_AGE_ID INTEGER NOT NULL REFERENCES AGENDAMENTO (AGE_ID) ON DELETE RESTRICT,
    OCO_TRA_ID INTEGER NOT NULL UNIQUE REFERENCES TRANSACAO (TRA_ID) ON DELETE CASCADE,
    OCO_NUMERO INTEGER NOT NULL CHECK (OCO_NUMERO > 0),
    PRIMARY KEY (OCO_AGE_ID, OCO_NUMERO)
);

CREATE INDEX IF NOT EXISTS IX_AGE_CON_ID ON AGENDAMENTO (AGE_CON_ID);
